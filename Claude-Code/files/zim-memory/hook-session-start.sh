#!/usr/bin/env bash
# Хук SessionStart для Claude Code: доиндексировать память и тихо обновить
# набор доработок.
#
# Запускается в начале сессии, чтобы поиск (zim-memory search) видел
# вчерашние заметки и прошлые сессии. Инкрементальный — читает jsonl
# с прошлого смещения, поэтому на неизменённых данных это доли секунды.
#
# Второе действие — обновление. Набор лежит поверх zim-claude, и когда
# апстрим обновляется, его install.sh затирает доработки. zim-deploy-update.sh
# подтягивает и апстрим, и сам набор, затем накладывает доработки заново.
# Он сам себя ограничивает по частоте (раз в час) и берёт flock, поэтому
# вызов на каждую сессию ничего не стоит.
#
# Оба действия не должны задерживать старт и не могут его сорвать: любой
# сбой = тихий выход с кодом 0.

set -uo pipefail

PY="${ZIM_MEMORY_PYTHON:-python3}"
UPDATE="$HOME/.local/bin/zim-deploy-update.sh"

# --- обновление: отдельным процессом, сразу ---------------------------------
#
# Именно в фоне: fetch в интернет может занять секунды, а сессия ждать не
# должна. nohup + полное отсоединение, чтобы процесс пережил закрытие
# терминала и не держал пайп хука открытым.
if [[ -x "$UPDATE" && "${ZIM_DEPLOY_NO_UPDATE:-0}" != "1" ]]; then
  nohup "$UPDATE" >/dev/null 2>&1 </dev/null &
  disown 2>/dev/null || true
fi

# --- индекс памяти ----------------------------------------------------------

SCRIPT="$HOME/.claude/zim-memory/index.py"
[[ -f "$SCRIPT" ]] || exit 0

command -v "$PY" >/dev/null 2>&1 || exit 0

timeout 60 "$PY" -I "$SCRIPT" index >/dev/null 2>&1 || true
exit 0
